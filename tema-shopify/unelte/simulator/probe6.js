const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome' });
  const p = await b.newPage({ viewport: { width: 390, height: 844 } });
  const errs = [];
  await p.route(/^https?:\/\/(?!localhost).*/, (r) => r.abort());
  await p.route('https://cdn.shopify.com/storefront/standard-events.js', (r) => r.fulfill({ contentType: 'application/javascript', body: '' }));
  await p.addInitScript(() => { window.Shopify = { designMode: false, currency: { active: 'RON', rate: '1.0' } }; });
  p.on('pageerror', (e) => errs.push(e.message));
  await p.goto('http://localhost:4567/pages/vivid', { waitUntil: 'networkidle' });
  const out = {};
  out.hiddenBefore = await p.$$eval('.c-preview[hidden]', (e) => e.length);
  await p.click('[data-load-more]');
  await p.waitForTimeout(300);
  out.hiddenAfter = await p.$$eval('.c-preview[hidden]', (e) => e.length);
  out.buttonGone = !(await p.$('[data-load-more]'));
  await p.click('.c-preview__zoom');
  await p.waitForTimeout(400);
  out.lightboxOpen = await p.$eval('dialog.c-lightbox', (d) => d.open);
  out.lbSrc = await p.$eval('.c-lightbox__image', (i) => i.getAttribute('src'));
  out.counter = await p.$eval('.c-lightbox__counter', (i) => i.textContent);
  await p.click('[data-lightbox-next]');
  out.lbSrc2 = await p.$eval('.c-lightbox__image', (i) => i.getAttribute('src'));
  await p.screenshot({ path: 'lightbox.png' });
  await p.keyboard.press('Escape');
  await p.waitForTimeout(200);
  out.lightboxClosed = !(await p.$eval('dialog.c-lightbox', (d) => d.open));
  out.bodyLocked = await p.evaluate(() => document.body.classList.contains('overflow-hidden'));
  await p.$eval('.c-vreviews', (e) => e.scrollIntoView());
  await p.waitForTimeout(800);
  out.videoSrc = await p.$eval('.c-vreview video source', (s) => s.getAttribute('src'));
  out.videoLoaded = await p.$eval('.c-vreview video', (v) => v.dataset.loaded);
  await p.click('.c-vreview [data-sound-toggle]');
  out.unmuted = await p.$eval('.c-vreview video', (v) => !v.muted);
  out.cardClass = await p.$eval('.c-vreview', (v) => v.className);
  out.errs = errs;
  console.log(JSON.stringify(out, null, 1));
  await b.close();
})();
